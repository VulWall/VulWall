#!/usr/bin/env bash
# Regenerates src/internal/shared/cdn_ranges.txt from the providers' published lists.
# The file is embedded in the binary (shared.CDNProvider); port ingestion uses it to skip
# nuclei port triggers for shared CDN edge addresses. Run it now and then, review the
# diff and commit. Needs curl and python3.
set -euo pipefail
out="$(cd "$(dirname "$0")/.." && pwd)/src/internal/shared/cdn_ranges.txt"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsS -m 30 https://www.cloudflare.com/ips-v4 -o "$tmp/cf4"
curl -fsS -m 30 https://www.cloudflare.com/ips-v6 -o "$tmp/cf6"
curl -fsS -m 30 https://api.fastly.com/public-ip-list -o "$tmp/fastly.json"
curl -fsS -m 60 https://ip-ranges.amazonaws.com/ip-ranges.json -o "$tmp/aws.json"
# Azure publishes its service tags as a weekly file whose URL changes; take it from the page.
azure_url="$(curl -fsSL -m 30 'https://www.microsoft.com/en-us/download/details.aspx?id=56519' |
	grep -oE 'https://download.microsoft.com/[^"]*ServiceTags_Public_[0-9]+\.json' | head -1)"
[ -n "$azure_url" ] || { echo "Azure service tags URL not found" >&2; exit 1; }
curl -fsSL -m 120 "$azure_url" -o "$tmp/azure.json"

python3 -I - "$tmp" "$out" <<'PY'
import datetime, ipaddress, json, sys
tmp, out = sys.argv[1], sys.argv[2]
rows = []
def add(provider, cidrs):
    cidrs = [c.strip() for c in cidrs if c.strip()]
    if not cidrs:
        sys.exit(f"{provider}: empty list")
    for c in cidrs:
        ipaddress.ip_network(c)  # fail on garbage
        rows.append((provider, c))
add("Cloudflare", open(f"{tmp}/cf4").read().split() + open(f"{tmp}/cf6").read().split())
f = json.load(open(f"{tmp}/fastly.json"))
add("Fastly", f["addresses"] + f.get("ipv6_addresses", []))
a = json.load(open(f"{tmp}/aws.json"))
# CLOUDFRONT only: CLOUDFRONT_ORIGIN_FACING is CloudFront's egress, and the rest of AWS is
# customer compute.
add("CloudFront", [p["ip_prefix"] for p in a["prefixes"] if p["service"] == "CLOUDFRONT"]
    + [p["ipv6_prefix"] for p in a["ipv6_prefixes"] if p["service"] == "CLOUDFRONT"])
z = json.load(open(f"{tmp}/azure.json"))
add("AzureFrontDoor", next(v for v in z["values"] if v["name"] == "AzureFrontDoor.Frontend")["properties"]["addressPrefixes"])
with open(out, "w") as w:
    w.write("# Shared CDN edge ranges: <provider> <cidr>. Generated by scripts/update-cdn-ranges.sh\n")
    w.write(f"# on {datetime.date.today()} from www.cloudflare.com/ips-v4 and ips-v6, api.fastly.com/public-ip-list,\n")
    w.write("# ip-ranges.amazonaws.com (service CLOUDFRONT) and Azure service tag AzureFrontDoor.Frontend.\n")
    w.write("# Do not edit by hand.\n")
    for p, c in sorted(set(rows), key=lambda r: (r[0], ipaddress.ip_network(r[1]).version, ipaddress.ip_network(r[1]))):
        w.write(f"{p} {c}\n")
print(f"{len(rows)} ranges -> {out}")
PY
